def pixmap(name: str, color: str, size: int = 20) -> QPixmap:
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="{color}" '
        f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{BODIES[name]}</svg>'
    )
    scale = 2
    result = QPixmap(size * scale, size * scale)
    result.fill(Qt.transparent)
    painter = QPainter(result)
    QSvgRenderer(QByteArray(svg.encode())).render(painter)
    painter.end()
    result.setDevicePixelRatio(scale)
    return result


def icon(name: str, color: str, size: int = 20, checked_color: str | None = None) -> QIcon:
    """An icon in one colour, optionally another when the button is checked."""
    result = QIcon()
    result.addPixmap(pixmap(name, color, size), QIcon.Normal, QIcon.Off)
    result.addPixmap(pixmap(name, checked_color or color, size), QIcon.Normal, QIcon.On)
    return result
